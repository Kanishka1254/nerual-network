# ==========================================
# STEP 2: DATA PREPROCESSING
# ==========================================

# Remove sequence ID if present

X = X.select_dtypes(include=[np.number])

# Encode target labels

encoder = LabelEncoder()

y_encoded = encoder.fit_transform(y.iloc[:, 0])

# Convert labels into categorical format

num_classes = len(np.unique(y_encoded))

y_categorical = to_categorical(
    y_encoded,
    num_classes=num_classes
)

# Normalize input features

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)

# ==========================================
# STEP 3: TRAIN TEST SPLITTING
# ==========================================

X_train, X_test, y_train, y_test = train_test_split(
    X_scaled,
    y_categorical,
    test_size=0.2,
    random_state=42,
    stratify=y_encoded
)

print("Training samples:", len(X_train))
print("Testing samples:", len(X_test))

# ==========================================
# STEP 4: BUILD NEURAL NETWORK
# ==========================================

model = Sequential([

    Dense(
        64,
        activation='relu',
        input_shape=(X_train.shape[1],)
    ),

    Dropout(0.2),

    Dense(
        32,
        activation='relu'
    ),

    Dense(
        16,
        activation='relu'
    ),

    Dense(
        num_classes,
        activation='softmax'
    )

])

# ==========================================
# STEP 5: COMPILE MODEL
# ==========================================

model.compile(

    optimizer='adam',

    loss='categorical_crossentropy',

    metrics=['accuracy']

)

model.summary()

# ==========================================
# STEP 6: TRAIN NEURAL NETWORK
# ==========================================

history = model.fit(

    X_train,

    y_train,

    epochs=100,

    batch_size=32,

    validation_split=0.2,

    verbose=1

)

# ==========================================
# STEP 7: MODEL EVALUATION
# ==========================================

loss, accuracy = model.evaluate(
    X_test,
    y_test,
    verbose=0
)

print("\nModel Evaluation")

print("Test Loss:", loss)

print("Test Accuracy:", accuracy * 100, "%")

# ==========================================
# STEP 8: PREDICTION
# ==========================================

